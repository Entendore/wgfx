use crate::math::{Vec2, Vec4};
use crate::renderer::{Batch2D, Shape2D, ShapeKind};

/// 5x7 bitmap font. Each character is represented as 5 bytes (columns),
/// where each byte's bits represent rows (bit 4 = top, bit 0 = bottom).
pub fn get_char_bits(c: char) -> [u8; 5] {
    match c {
        'A' => [0x0E, 0x11, 0x1F, 0x11, 0x11],
        'B' => [0x1E, 0x11, 0x1E, 0x11, 0x1E],
        'C' => [0x0E, 0x11, 0x10, 0x11, 0x0E],
        'D' => [0x1E, 0x11, 0x11, 0x11, 0x1E],
        'E' => [0x1F, 0x10, 0x1E, 0x10, 0x1F],
        'F' => [0x1F, 0x10, 0x1E, 0x10, 0x10],
        'G' => [0x0E, 0x11, 0x10, 0x13, 0x0F],
        'H' => [0x11, 0x11, 0x1F, 0x11, 0x11],
        'I' => [0x0E, 0x04, 0x04, 0x04, 0x0E],
        'J' => [0x07, 0x02, 0x02, 0x12, 0x0C],
        'K' => [0x11, 0x12, 0x1C, 0x12, 0x11],
        'L' => [0x10, 0x10, 0x10, 0x10, 0x1F],
        'M' => [0x11, 0x1B, 0x15, 0x11, 0x11],
        'N' => [0x11, 0x19, 0x15, 0x13, 0x11],
        'O' => [0x0E, 0x11, 0x11, 0x11, 0x0E],
        'P' => [0x1E, 0x11, 0x1E, 0x10, 0x10],
        'Q' => [0x0E, 0x11, 0x11, 0x15, 0x0E],
        'R' => [0x1E, 0x11, 0x1E, 0x12, 0x11],
        'S' => [0x0F, 0x10, 0x0E, 0x01, 0x1E],
        'T' => [0x1F, 0x04, 0x04, 0x04, 0x04],
        'U' => [0x11, 0x11, 0x11, 0x11, 0x0E],
        'V' => [0x11, 0x11, 0x11, 0x0A, 0x04],
        'W' => [0x11, 0x11, 0x15, 0x1B, 0x11],
        'X' => [0x11, 0x0A, 0x04, 0x0A, 0x11],
        'Y' => [0x11, 0x11, 0x0A, 0x04, 0x04],
        'Z' => [0x1F, 0x01, 0x02, 0x04, 0x1F],
        '0' => [0x0E, 0x11, 0x13, 0x15, 0x0E],
        '1' => [0x04, 0x0C, 0x04, 0x04, 0x0E],
        '2' => [0x0E, 0x11, 0x02, 0x04, 0x1F],
        '3' => [0x1F, 0x02, 0x0E, 0x01, 0x1E],
        '4' => [0x02, 0x06, 0x0A, 0x1F, 0x02],
        '5' => [0x1F, 0x10, 0x1E, 0x01, 0x1E],
        '6' => [0x06, 0x08, 0x1E, 0x11, 0x0E],
        '7' => [0x1F, 0x01, 0x02, 0x04, 0x08],
        '8' => [0x0E, 0x11, 0x0E, 0x11, 0x0E],
        '9' => [0x0E, 0x11, 0x0F, 0x01, 0x02],
        ' ' => [0x00, 0x00, 0x00, 0x00, 0x00],
        ':' => [0x00, 0x04, 0x00, 0x04, 0x00],
        '.' => [0x00, 0x00, 0x00, 0x00, 0x04],
        ',' => [0x00, 0x00, 0x00, 0x0C, 0x04],
        '-' => [0x00, 0x00, 0x1F, 0x00, 0x00],
        '+' => [0x00, 0x04, 0x0E, 0x04, 0x00],
        '/' => [0x01, 0x02, 0x04, 0x08, 0x10],
        '\\' => [0x10, 0x08, 0x04, 0x02, 0x01],
        '(' => [0x02, 0x04, 0x08, 0x04, 0x02],
        ')' => [0x08, 0x04, 0x02, 0x04, 0x08],
        '[' => [0x0E, 0x08, 0x08, 0x08, 0x0E],
        ']' => [0x0E, 0x02, 0x02, 0x02, 0x0E],
        '!' => [0x04, 0x04, 0x04, 0x00, 0x04],
        '?' => [0x0E, 0x11, 0x02, 0x00, 0x04],
        '\'' => [0x04, 0x04, 0x00, 0x00, 0x00],
        '"' => [0x0A, 0x0A, 0x00, 0x00, 0x00],
        '<' => [0x02, 0x04, 0x08, 0x04, 0x02],
        '>' => [0x08, 0x04, 0x02, 0x04, 0x08],
        '=' => [0x00, 0x1F, 0x00, 0x1F, 0x00],
        '*' => [0x00, 0x0A, 0x04, 0x0A, 0x00],
        '#' => [0x0A, 0x1F, 0x0A, 0x1F, 0x0A],
        '%' => [0x18, 0x19, 0x02, 0x09, 0x03],
        '&' => [0x0E, 0x11, 0x0A, 0x15, 0x1A],
        '@' => [0x0E, 0x11, 0x15, 0x10, 0x0E],
        '_' => [0x00, 0x00, 0x00, 0x00, 0x1F],
        '|' => [0x04, 0x04, 0x04, 0x04, 0x04],
        '~' => [0x00, 0x08, 0x1F, 0x02, 0x00],
        '^' => [0x04, 0x0A, 0x00, 0x00, 0x00],
        '`' => [0x08, 0x04, 0x00, 0x00, 0x00],
        ';' => [0x00, 0x04, 0x00, 0x0C, 0x04],
        '$' => [0x04, 0x0E, 0x15, 0x0E, 0x04],
        '{' => [0x06, 0x08, 0x0C, 0x08, 0x06],
        '}' => [0x0C, 0x02, 0x06, 0x02, 0x0C],
        _ => [0x1F, 0x11, 0x11, 0x11, 0x1F], // Unknown char = box
    }
}

/// Pushes text into the batch renderer. Characters are 5x5 pixels at scale 1.
/// Character spacing is 6 pixels, line height is 7 pixels.
pub fn push_text(batch: &mut Batch2D, text: &str, x: f32, y: f32, scale: f32, color: Vec4) {
    let mut cur_x = x;
    let mut cur_y = y;
    for c in text.chars() {
        if c == '\n' {
            cur_x = x;
            cur_y += 7.0 * scale;
            continue;
        }
        let upper = c.to_uppercase().next().unwrap_or(c);
        let bits = get_char_bits(upper);
        for (row, r_bits) in bits.iter().enumerate() {
            for col in 0..5 {
                if (r_bits >> (4 - col)) & 1 == 1 {
                    batch.push(Shape2D {
                        pos: Vec2::new(cur_x + col as f32 * scale, cur_y + row as f32 * scale),
                        size: Vec2::new(scale, scale),
                        color,
                        kind: ShapeKind::Rect,
                        rot: 0.0,
                    });
                }
            }
        }
        cur_x += 6.0 * scale;
    }
}

/// Measures the width and height of rendered text.
pub fn measure_text(text: &str, scale: f32) -> Vec2 {
    let lines: Vec<&str> = text.split('\n').collect();
    let max_width = lines
        .iter()
        .map(|line| line.len() as f32 * 6.0 * scale)
        .fold(0.0f32, |a, b| a.max(b));
    let height = lines.len() as f32 * 7.0 * scale;
    Vec2::new(max_width, height)
}
